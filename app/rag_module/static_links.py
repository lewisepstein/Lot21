def get_links_as_string(keys):
    """
    Returns a formatted string of links for the given keys.
    keys can be a single key (e.g. "solutions") or a list of keys.
    """
    if isinstance(keys, str):
        keys = [keys]
    
    output = []
    
    for key in keys:
        if key in FALLBACK_LINKS:
            data = FALLBACK_LINKS[key]
            # Handle nested dictionaries (like resources and policy)
            if any(isinstance(v, dict) for v in data.values()):
                for subkey, subdata in data.items():
                    output.append(f"\n[{subkey.upper()}]")
                    for name, url in subdata.items():
                        output.append(f"- {name}: {url}")
            else:
                # Handle flat dictionaries
                output.append(f"\n[{key.upper().replace('_', ' ')}]")
                for name, url in data.items():
                    output.append(f"- {name}: {url}")
                    
    return "\n".join(output)
